'''Modulo math para trabajar las matematicas'''
import math

# Redondeado hacia el piso
resultado = math.floor(3.7)
print(resultado)

# Redondeado hacia arriba
resultado = math.ceil(3.7)
print(resultado)

# Letra PI
resultado = math.pi
print(resultado)

# Trigonometria
# logaritmo (Exponer un número para que de ese resultado )
resultado = math.log(25, 5)
print(resultado)

# seno
resultado = math.sin(math.radians(30))
print(resultado)

# coseno
resultado = math.cos(math.radians(30))
print(resultado)

# tangente
resultado = math.tan(math.radians(30))
print(resultado)
