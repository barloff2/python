'''Documentación https://www.datacamp.com/es/tutorial/loc-vs-iloc'''

system('cls')

# Seleccionar la columna "Kilometraje"
print(ventas_autos["Kilometraje"])

# Encontrar el valor medio de las columnas "Kilometraje"
print(ventas_autos["Kilometraje"].mean())

# Seleccionar aquellas columnas que tengan valores superiores a 100,000 kilómetros en la columna Kilometraje
print(ventas_autos[ventas_autos["Kilometraje"] > 100000])

# Creamos una tabla cruzada de doble entrada entre Fabricante y cantidad de puertas
tabla_cruzada = pd.crosstab(ventas_autos["Fabricante"], ventas_autos["Puertas"])
print(tabla_cruzada)

# Agrupamos las columnas por fabricante y buscando el valor medio de las columnas numéricas
agrupado = ventas_autos.groupby(["Fabricante"]).mean(numeric_only=True)
print(agrupado)

# Importamos MatPlotlib y creamos un gráfico con los valores de la columna Kilometraje
system('cls')
import matplotlib.pyplot as plt

ventas_autos['Kilometraje'].plot()
plt.title('Kilometraje de Vehículos')
plt.ylabel('Kilometraje')
plt.xlabel('Índice')
plt.show()

# Puede que un gráfico más apropiado en este caso sea un histograma
ventas_autos['Kilometraje'].hist()
plt.title('Distribución de Kilometraje')
plt.xlabel('Kilometraje')
plt.ylabel('Frecuencia')
plt.show()


# Elimina la puntuación de la columna de precios
ventas_autos['Precio (USD)'] = ventas_autos['Precio (USD)'].str.replace('[\,\$\.]', '', regex=True).astype(float)

# Intentamos graficar la columna de precios
ventas_autos['Precio (USD)'].plot()
plt.title('Precios de Vehículos')
plt.ylabel('Precio')
