print(ventas_autos.dtypes)

# Aplicamos estadística descriptiva (cantidad de valores, media, desviación estándar, valores mínimos y máximos, cuartiles) al dataset
print(ventas_autos.describe())

# Obtenemos información del dataset utilzado info()
print(ventas_autos.info())

